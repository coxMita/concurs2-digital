//! Question images: type checked by magic bytes, size-limited, random file names.

use std::path::{Path, PathBuf};

use crate::services::credentials::random_token;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ImageKind {
    Png,
    Jpeg,
    Webp,
}

impl ImageKind {
    pub fn ext(self) -> &'static str {
        match self {
            Self::Png => "png",
            Self::Jpeg => "jpg",
            Self::Webp => "webp",
        }
    }
}

/// Detects PNG, JPEG or WebP from the first bytes; anything else is rejected.
pub fn sniff(bytes: &[u8]) -> Option<ImageKind> {
    if bytes.starts_with(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A]) {
        Some(ImageKind::Png)
    } else if bytes.starts_with(&[0xFF, 0xD8, 0xFF]) {
        Some(ImageKind::Jpeg)
    } else if bytes.len() >= 12 && &bytes[0..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        Some(ImageKind::Webp)
    } else {
        None
    }
}

/// File names are generated by us; reject anything else to avoid path traversal.
fn is_safe_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() < 80
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '.')
        && !name.starts_with('.')
}

fn path_of(dir: &Path, name: &str) -> Option<PathBuf> {
    is_safe_name(name).then(|| dir.join(name))
}

#[derive(Debug, thiserror::Error)]
pub enum UploadError {
    #[error("Imaginea depășește dimensiunea maximă permisă ({0} MB).")]
    TooLarge(usize),
    #[error("Format neacceptat. Folosiți imagini PNG, JPG sau WebP.")]
    BadType,
    #[error("Imaginea nu a putut fi salvată.")]
    Io(#[from] std::io::Error),
}

/// Validates and stores an image; returns the generated file name.
pub async fn save(dir: &Path, bytes: &[u8], max_bytes: usize) -> Result<String, UploadError> {
    if bytes.len() > max_bytes {
        return Err(UploadError::TooLarge(max_bytes / (1024 * 1024)));
    }
    let kind = sniff(bytes).ok_or(UploadError::BadType)?;
    let name = format!("{}.{}", random_token(24), kind.ext());
    tokio::fs::create_dir_all(dir).await?;
    tokio::fs::write(dir.join(&name), bytes).await?;
    Ok(name)
}

/// Copies an existing image to a new random name.
pub async fn copy(dir: &Path, name: &str) -> Option<String> {
    let src = path_of(dir, name)?;
    let ext = name.rsplit('.').next().unwrap_or("png");
    let new = format!("{}.{}", random_token(24), ext);
    tokio::fs::copy(src, dir.join(&new)).await.ok()?;
    Some(new)
}

pub async fn remove(dir: &Path, name: &str) {
    if let Some(p) = path_of(dir, name)
        && let Err(e) = tokio::fs::remove_file(&p).await
    {
        tracing::warn!("could not remove upload {name}: {e}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sniffing() {
        assert_eq!(sniff(b"\x89PNG\r\n\x1a\nrest"), Some(ImageKind::Png));
        assert_eq!(sniff(b"\xFF\xD8\xFF\xE0"), Some(ImageKind::Jpeg));
        assert_eq!(sniff(b"RIFF\0\0\0\0WEBPVP8 "), Some(ImageKind::Webp));
        assert_eq!(sniff(b"<svg xmlns=..."), None);
        assert_eq!(sniff(b"GIF89a"), None);
    }

    #[test]
    fn safe_names() {
        assert!(is_safe_name("abc123.png"));
        assert!(!is_safe_name("../etc/passwd"));
        assert!(!is_safe_name(".hidden"));
        assert!(!is_safe_name("a/b.png"));
    }
}
